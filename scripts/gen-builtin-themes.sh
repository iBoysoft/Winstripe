#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
python3 - "$@" <<'PY'
import json
import pathlib
import sys

root = pathlib.Path(".")
entries = []
for file in sorted((root / "Themes").glob("*.json")):
    text = file.read_text().rstrip()
    def reject_duplicates(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"{file}: duplicate key {key!r}")
            result[key] = value
        return result
    try:
        value = json.loads(text, object_pairs_hook=reject_duplicates)
    except ValueError as error:
        print(error, file=sys.stderr)
        sys.exit(1)
    theme_id = value.get("id")
    if not isinstance(theme_id, str) or not theme_id:
        raise ValueError(f"{file}: missing string id")
    entries.append((theme_id, file, text))
lines = ["// Generated by scripts/gen-builtin-themes.sh. Do not edit.", "enum BuiltinThemes {", "    static let json: [String: String] = ["]
seen = set()
for theme_id, file, text in sorted(entries, key=lambda item: item[0]):
    if theme_id in seen:
        raise ValueError(f"duplicate built-in theme id {theme_id!r}")
    seen.add(theme_id)
    hashes = "#"
    while '"""' + hashes in text or "\\" + hashes + "(" in text:
        hashes += "#"
    lines += [f'        "{theme_id}": {hashes}"""', text, f'"""{hashes},']
lines += ["    ]", "}", ""]
generated = "\n".join(lines)
target = root / "Sources/Winstripe/BuiltinThemes.swift"
if sys.argv[1:] == ["--check"]:
    if not target.exists() or target.read_text() != generated:
        print("BuiltinThemes.swift is out of date", file=sys.stderr)
        sys.exit(1)
elif sys.argv[1:]:
    sys.exit("usage: gen-builtin-themes.sh [--check]")
else:
    target.write_text(generated)
PY
